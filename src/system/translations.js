export const translate = (language, value, variables = {}) => {
  if (typeof value !== 'string') return value;
  let translated = language === 'bn' ? (banglaTranslations[value] || value) : value;
  Object.entries(variables).forEach(([key, replacement]) => {
    translated = translated.replaceAll('{' + key + '}', String(replacement));
  });
  return translated;
};
